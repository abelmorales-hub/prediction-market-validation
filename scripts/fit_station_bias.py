"""Fit the station-bias correction, on data the next study will not be tested on.

Run: uv run python -m scripts.fit_station_bias [--until-day 2026-10-08] [--write]

H2 lost G3 by 0.1008 in mean paired Brier (docs/g3_result.md), and the diagnosis was
location rather than ignorance: ECE 0.171 against the market's 0.049, AUC at chance inside
every price bucket. A 0.25-degree grid cell is not a named station, and the venue settles
on the station. This script measures that offset.

**Where the training data may come from, and why.** Two sources, both unusable as a test
set and therefore free to fit on:

  * days before 2026-09-20 -- never part of any sample, excluded by Amendment 10;
  * days inside the frozen G3 window -- spent. Their outcomes have been read, so nothing
    fitted by anyone who has seen docs/g3_result.md can be tested on them again. Using
    them as training data costs nothing that was not already gone.

The cutoff is what matters: `--until-day` must fall strictly before the new window opens,
or the correction gets fitted on the rows meant to judge it. That is the one mistake this
script exists to prevent, so the cutoff is recorded in the file it generates.

**The estimator is a per-station constant, deliberately.** One parameter per station: the
median of (settled - ensemble median) over pinned days. A median because a single
mis-grouped ladder must not move it, and a constant because the correction has to be
declared and frozen before the window opens -- anything with more freedom would need its
own pre-registration to stop it being retuned later. Stations with too few pinned days take
the pooled offset rather than a loud estimate from three observations.
"""

from __future__ import annotations

import argparse
import statistics
import subprocess
import sys
from datetime import UTC, date, datetime, timedelta
from pathlib import Path
from typing import Any

from src.analysis.settlement import group_by_station_day, settlement_interval
from src.config import get_settings
from src.storage.supabase_repo import Repo, connect

# Below this many pinned days a station takes the pooled offset. Three observations of a
# two-degree-wide target do not identify a one-degree bias, and pretending otherwise would
# put the noisiest corrections on the least-observed stations.
MIN_DAYS_FOR_OWN_OFFSET = 8

OUT_PATH = Path("src/models/station_bias.py")

# `KXHIGH%` is load-bearing, not tidiness. A station-day carries a minimum-temperature
# ladder beside the maximum one (`KXLOWTATL` next to `KXHIGHTATL`), they share the
# (station, settles_on) key, and intersecting a max with a min empties the interval: 379
# of 649 ladders came out contradictory before this filter existed. It is also exactly the
# rule the H2 forecaster applies to decide which markets it can answer at all.
SERIES_PREFIX = "KXHIGH"

RESOLVED_RUNGS = """
select m.settlement_station, m.settles_on, m.end_date, m.series_id,
       m.strike_type, m.floor_strike, m.cap_strike, o.outcome
from markets m
join outcomes o using (market_id)
where m.settlement_station is not null
  and m.settles_on is not null
  and m.settles_on <= %s
  and m.strike_type is not null
  and m.series_id like 'KXHIGH%%'
order by m.settlement_station, m.settles_on
"""


def _git_sha() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except Exception:  # noqa: BLE001 - provenance is better empty than fatal
        return "unknown"


def _render(
    offsets: dict[str, float],
    pooled: float,
    counts: dict[str, int],
    until_day: date,
    days: int,
) -> str:
    """Generate the frozen module.

    Source rather than JSON, for two reasons: a model in this project reads no files and
    touches no clock (see `src.models.weather`), and a dict literal at a commit is a freeze
    that `git log` can prove. The numbers are the artefact; this file is their only home.
    """
    lines = [
        '"""Per-station bias of the raw GEFS ensemble against the settlement observation.',
        "",
        "GENERATED by scripts/fit_station_bias.py -- do not edit by hand.",
        "",
        "Positive means the station settles *hotter* than the grid cell forecast, so the",
        "correction is added to every ensemble member before the strike arithmetic. One",
        "constant per station: fitted once, frozen with the model_version that uses it.",
        "Changing a number here is a new model_version and a new amendment, never an edit",
        "-- the same rule the H2 files live under.",
        "",
        f"Fitted on station-days settling on or before {until_day.isoformat()}:",
        f"{days} pinned station-days. Those days are either pre-sample or spent, and the",
        "fitting script explains why neither can serve as a test set again.",
        "",
        f"Fit at {datetime.now(UTC):%Y-%m-%dT%H:%M:%SZ} from commit {_git_sha()}.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f"# Stations with fewer than {MIN_DAYS_FOR_OWN_OFFSET} pinned days use this instead.",
        f"POOLED_OFFSET_F = {pooled:+.3f}",
        "",
        f'FIT_THROUGH = "{until_day.isoformat()}"',
        "",
        "OFFSET_F: dict[str, float] = {",
    ]
    for station in sorted(offsets):
        n = counts.get(station, 0)
        note = "" if n >= MIN_DAYS_FOR_OWN_OFFSET else "  <- pooled, too few days"
        lines.append(f'    "{station}": {offsets[station]:+.3f},  # n={n}{note}')
    lines += [
        "}",
        "",
        "",
        "def offset_for(station: str) -> float:",
        '    """The correction for a station, pooled for one that was never fitted.',
        "",
        "    Never raises. A station joining the universe after the fit is a real",
        "    possibility -- New Orleans was added mid-study once -- and the pooled offset is",
        "    a defensible answer where a KeyError would silently cost that station its rows.",
        '    """',
        "    return OFFSET_F.get(station, POOLED_OFFSET_F)",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--until-day",
        default="2026-10-08",
        help="fit only on station-days settling on or before this date; must fall strictly "
        "before the new collection window opens",
    )
    ap.add_argument("--write", action="store_true", help=f"write {OUT_PATH} (default: dry run)")
    args = ap.parse_args()

    until_day = date.fromisoformat(args.until_day)
    cfg = get_settings()
    if not cfg.supabase_db_url:
        print("SUPABASE_DB_URL not set", file=sys.stderr)
        return 2

    with connect(cfg.supabase_db_url) as conn:
        repo = Repo(conn)
        with conn.cursor() as cur:
            cur.execute(RESOLVED_RUNGS, (until_day,))
            rows: list[dict[str, Any]] = list(cur.fetchall())

        # Filtered twice, in the query and here. The query is the optimisation; this is
        # the one that documents the invariant at the point it matters.
        ladders = group_by_station_day(rows, series_prefix=SERIES_PREFIX)
        by_station: dict[str, list[float]] = {}
        skipped = {"not_pinned": 0, "contradictory": 0, "no_ensemble": 0}

        for (station, day), rungs in sorted(ladders.items()):
            settled = settlement_interval(rungs)
            if settled.low > settled.high:
                skipped["contradictory"] += 1
                continue
            if not settled.pinned:
                skipped["not_pinned"] += 1
                continue

            # The same instant and the same lookup the forecaster will use, so the bias
            # measured is the bias at the lead time being corrected. `end_date` names the
            # day *after* the forecast day, which is why it anchors the horizon.
            horizon = min(r["end_date"] for r in rungs) - timedelta(hours=24)
            ensemble = repo.latest_ensemble_before(station, day, horizon)
            if ensemble is None:
                skipped["no_ensemble"] += 1
                continue

            forecast = statistics.median(float(v) for v in ensemble["tmax_f"])
            by_station.setdefault(station, []).append(settled.midpoint - forecast)

    if not by_station:
        print("no pinned station-days with an ensemble; nothing to fit", file=sys.stderr)
        return 1

    counts = {s: len(v) for s, v in by_station.items()}
    pooled = statistics.median([d for v in by_station.values() for d in v])
    offsets = {
        s: (statistics.median(v) if len(v) >= MIN_DAYS_FOR_OWN_OFFSET else pooled)
        for s, v in by_station.items()
    }
    total_days = sum(counts.values())

    print(f"ladders        : {len(ladders)}")
    print(f"pinned + fitted: {total_days}")
    print("skipped        : " + "  ".join(f"{k}={v}" for k, v in skipped.items()))
    print(f"pooled offset  : {pooled:+.3f} F")
    print()
    print(f"{'station':9s} {'n':>4s} {'offset':>8s} {'spread':>8s}")
    for station in sorted(by_station):
        diffs = by_station[station]
        spread = statistics.pstdev(diffs) if len(diffs) > 1 else float("nan")
        own = "" if counts[station] >= MIN_DAYS_FOR_OWN_OFFSET else "  (pooled)"
        print(f"{station:9s} {counts[station]:4d} {offsets[station]:+8.3f} {spread:8.3f}{own}")

    if not args.write:
        print(f"\ndry run. Pass --write to generate {OUT_PATH}.")
        return 0

    OUT_PATH.write_text(_render(offsets, pooled, counts, until_day, total_days), encoding="utf-8")
    print(f"\nwrote {OUT_PATH} -- commit it, then freeze it by amendment.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
